def main():
    with io.open(QUESTIONS, encoding='utf-8') as f:
        data = json.load(f)

    existing = {q['stem'] for q in data['questions']}  # 去重：题干完全相同的跳过
    next_no = len(data['questions']) + 1  # 接在现有题号后面
    added = {'tax-system': 0, 'vat': 0, 'income-tax': 0, 'admin': 0}

    for group in (TAX_SYSTEM, VAT, INCOME_TAX, ADMIN):
        for topic, qtype, stem, options, answer, explain in group:
            if stem in existing:  # 已有同题
                continue
            if qtype == 'single' and len(answer) != 1:  # 单选题只能一个答案
                raise SystemExit('单选题答案数不对：' + stem)
            if answer and max(answer) >= len(options):  # 答案索引越界
                raise SystemExit('答案索引越界：' + stem)
            data['questions'].append({
                'id': 'q%02d' % next_no,
                'topic': topic,
                'type': qtype,
                'stem': stem,
                'options': options,
                'answer': answer,
                'explain': explain,
            })
            existing.add(stem)
            added[topic] += 1
            next_no += 1

    data['meta']['version'] = '0.4.0'
    data['meta']['note'] = (
        '现有 %d 题，覆盖税务/金融/经管三个方向的 8 个知识板块。'
        '题目均按现行税法条文与考试大纲编写，非官方真题；'
        '考点参照公开的院校复试回忆版（中南财、人大、上财、复旦、政法等）选取，'
        '题目与解析为本工程自写，未复制任何机构题库原文。'
    ) % len(data['questions'])

    with io.open(QUESTIONS, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)

    print('新增：', added)
    print('总题数：', len(data['questions']))


if __name__ == '__main__':
    main()
