def main():
    with io.open(BANKS, encoding='utf-8') as f:
        data = json.load(f)

    groups = {'law': LAW, 'cs': CS, 'med': MED}
    report = {}
    for key, items in groups.items():
        bank = data[key]
        existing = {q['stem'] for q in bank['questions']}  # 去重
        topic_ids = {t['id'] for t in bank['topics']}  # 允许的板块
        next_no = len(bank['questions']) + 1
        added = 0
        for topic, qtype, stem, options, answer, explain in items:
            if stem in existing:
                continue
            if topic not in topic_ids:
                raise SystemExit('%s 板块不存在：%s' % (key, topic))
            if qtype == 'single' and len(answer) != 1:
                raise SystemExit('%s 单选题答案数不对：%s' % (key, stem))
            if answer and max(answer) >= len(options):
                raise SystemExit('%s 答案越界：%s' % (key, stem))
            bank['questions'].append({
                'id': '%s%02d' % (key, next_no),
                'topic': topic,
                'type': qtype,
                'stem': stem,
                'options': options,
                'answer': answer,
                'explain': explain,
            })
            existing.add(stem)
            added += 1
            next_no += 1
        report[key] = (added, len(bank['questions']))

    with io.open(BANKS, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)

    for key, (added, total) in report.items():
        print('%s：新增 %d 题，现有 %d 题' % (key, added, total))


if __name__ == '__main__':
    main()
