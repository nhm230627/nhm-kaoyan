//  LegalView.swift —— 隐私政策与用户协议                            // 文件说明
//  为什么要有这一页：App Store 审核要求 App 内能直接看到隐私政策，光在商店页挂链接不够。
//  内容必须与实际行为一致：本工程会上传面试作答文本、不上传录音、没有账号体系，
//  下面每一条都照这三件事写，不写「我们可能收集…」这种含糊话。                // 内容约束

import SwiftUI  // 界面框架

struct LegalView: View {  // 隐私与协议
    @State private var tab = 0  // 0 隐私政策，1 用户协议

    var body: some View {  // 视图主体
        ScrollView {  // 可滚动
            VStack(alignment: .leading, spacing: Space.l) {  // 纵向排列
                Picker("文档", selection: $tab) {  // 两个 Tab
                    Text("隐私政策").tag(0)  // 隐私政策
                    Text("用户协议").tag(1)  // 用户协议
                }  // 选择器结束
                .pickerStyle(.segmented)  // 分段样式

                Text("最近更新：2026 年 11 月 3 日")  // 版本日期
                    .font(AppFont.caption)  // 小字
                    .foregroundStyle(Color.textTertiary)  // 弱化色

                if tab == 0 { privacy } else { terms }  // 按 Tab 显示
            }  // 排列结束
            .padding(Metrics.pagePadding)  // 内边距
            .padding(.bottom, Space.xxl)  // 底部留白
        }  // 滚动结束
        .background(Color.appBG)  // 底色
        .navigationTitle("隐私与协议")  // 标题
    }  // body 结束

    // MARK: - 隐私政策                                                  // 分节：隐私

    private var privacy: some View {  // 隐私政策全文
        VStack(alignment: .leading, spacing: Space.l) {  // 纵向排列
            section(  // 一、我们收集什么
                "一、我们会处理哪些信息",  // 小节标题
                """
                1. 你主动填写的信息：备考方向、备考阶段、目标院校（可以留空）、面试中的作答文字。
                2. 使用过程中产生的信息：答题记录、错题、闯关星级、成长值、伙伴状态、会员权益状态。
                3. 我们不会收集：通讯录、位置、照片、剪贴板、广告标识符（IDFA）。
                """
            )  // 第一节结束

            section(  // 二、语音怎么处理
                "二、语音数据怎么处理",  // 小节标题
                """
                语音作答使用系统自带的语音识别，优先在本机完成识别。录音不会被保存，也不会上传到我们的服务器。

                如果你在系统设置里允许了「改进语音识别」，部分识别请求可能由 Apple 的语音服务处理，那部分适用 Apple 的隐私政策，不由我们控制。
                """
            )  // 第二节结束

            section(  // 三、什么时候数据会离开设备
                "三、什么情况下数据会离开这台设备",  // 小节标题
                """
                只有一种情况：你使用「AI 模拟面试」时。

                此时你的作答文字、当前题目与所处环节会发送到我们自建的服务端，再转交模型服务生成追问与评分建议。发送内容不包含你的姓名、手机号或其它身份信息——本 App 没有账号体系，我们也拿不到这些。

                这些内容只用于当场生成反馈，不用于训练模型，也不出售给任何第三方。
                """
            )  // 第三节结束

            section(  // 四、数据存在哪里
                "四、数据存在哪里、存多久",  // 小节标题
                """
                学习记录、错题、伙伴状态、权益状态全部保存在这台设备上（文件名 appstate.json）。

                我们没有云端备份，也没有账号可以登录。卸载 App 或执行「重置本地数据」后，这些内容即被删除，且无法找回。
                """
            )  // 第四节结束

            section(  // 五、第三方
                "五、涉及的第三方",  // 小节标题
                """
                Apple：负责 App 内购买与支付处理；语音识别在开启系统开关时可能由 Apple 处理。

                模型服务提供方：仅接收作答文字与题目上下文用于生成评分，不接收身份信息。

                除上述两方外，我们不向任何其他方提供你的数据。
                """
            )  // 第五节结束

            section(  // 六、你的权利
                "六、你对自己的数据有什么权利",  // 小节标题
                """
                查看：所有数据都在 App 内可见（我的 → 统计与成长来源、错题本、面试记录）。

                删除：我的 → 重置本地数据，一键清空全部记录，立即生效。

                由于本 App 不提供账号，因此不存在「注销账号」这一操作，也不需要申请。
                """
            )  // 第六节结束

            section(  // 七、未成年人
                "七、未成年人",  // 小节标题
                """
                本 App 面向研究生入学考试的备考人群，不面向 14 岁以下的儿童。我们不会主动收集儿童的个人信息。
                """
            )  // 第七节结束

            section(  // 八、联系方式
                "八、政策变更与联系方式",  // 小节标题
                """
                本政策如有更新，会在 App 内以显著方式提示，并更新页面顶部的日期。

                如对隐私有疑问，或希望我们说明某条数据处理方式，可通过 App Store 商品页的「App 支持」链接联系我们。
                """
            )  // 第八节结束
        }  // 排列结束
    }  // privacy 结束

    // MARK: - 用户协议                                                  // 分节：协议

    private var terms: some View {  // 用户协议全文
        VStack(alignment: .leading, spacing: Space.l) {  // 纵向排列
            section(  // 一、服务内容
                "一、这是什么服务",  // 小节标题
                """
                本 App 是考研复试的备考训练工具，提供题库练习、闯关复习、AI 模拟面试、复盘报告与成长记录。
                """
            )  // 第一节结束

            section(  // 二、不构成承诺
                "二、关于 AI 评分的重要说明",  // 小节标题
                """
                App 内的「面试导师」是 AI 模拟角色，不是真实导师；五维评分是训练用的量表，不是招生单位的官方评分，也不能预测录取结果。

                复试小组人数与面试时长参考教育部《2026 年全国硕士研究生招生工作管理规定》。具体政策与要求，一律以你报考单位当年发布的官方文件为准。

                AI 生成的点评与建议可能出错，请与教材、招生简章交叉核对后再采信。
                """
            )  // 第二节结束

            section(  // 三、数据与账号
                "三、数据与账号",  // 小节标题
                """
                本 App 不需要注册，也没有账号。学习数据只存在你的设备上，卸载即丢失，我们无法帮你恢复，请自行留意。
                """
            )  // 第三节结束

            section(  // 四、会员与支付
                "四、会员与内购",  // 小节标题
                """
                会员通过 Apple 内购购买，支付由 Apple 处理，我们不接触你的支付信息。

                订阅类会员到期前会自动续期，可在 iOS「设置 → Apple ID → 订阅」中随时取消。退款申请由 Apple 按其一贯政策处理。
                """
            )  // 第四节结束

            section(  // 五、使用规范
                "五、使用规范",  // 小节标题
                """
                请勿对本 App 进行破解、反向工程、批量抓取题库或用于任何违法用途。题库内容仅供个人备考使用。
                """
            )  // 第五节结束

            section(  // 六、免责
                "六、责任范围",  // 小节标题
                """
                我们会尽力保证题库与解析的准确性，但不对因使用本 App 产生的考试结果承担责任。本 App 是辅助工具，不替代系统学习与官方信息。
                """
            )  // 第六节结束

            section(  // 七、协议变更
                "七、协议变更与联系方式",  // 小节标题
                """
                协议更新会在 App 内提示。继续使用即视为接受更新后的条款。

                如有疑问，可通过 App Store 商品页的「App 支持」链接联系我们。
                """
            )  // 第七节结束
        }  // 排列结束
    }  // terms 结束

    // MARK: - 小节组件                                                  // 分节：小节

    private func section(_ title: String, _ body: String) -> some View {  // 一个小节
        Card {  // 白卡
            VStack(alignment: .leading, spacing: Space.xs) {  // 纵向排列
                Text(title).font(AppFont.section)  // 小节标题
                Text(body)  // 正文
                    .font(AppFont.caption)  // 小字
                    .foregroundStyle(Color.textSecondary)  // 次要色
                    .lineSpacing(4)  // 行距松一点好读
                    .fixedSize(horizontal: false, vertical: true)  // 允许换行
            }  // 排列结束
        }  // 卡片结束
    }  // section 结束
}  // LegalView 结束
